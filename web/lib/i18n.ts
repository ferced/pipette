import tax from "./taxonomy.json";
import type { Lang } from "./types";

export const LANGS: Lang[] = ["en", "es"];
export const isLang = (s: string): s is Lang => s === "en" || s === "es";

/** Prefix a path for a language. English lives at the root. */
export const href = (lang: Lang, path: string) => (lang === "en" ? path : `/es${path === "/" ? "" : path}`);

type Field = (typeof tax.fields)[number];
export const FIELDS: Field[] = tax.fields;
export const FIELD = Object.fromEntries(tax.fields.map((f) => [f.id, f])) as Record<string, Field>;

export function fieldName(id: string, lang: Lang) {
  return FIELD[id]?.[lang] ?? id;
}
export function topicName(field: string, topic: string, lang: Lang) {
  const t = FIELD[field]?.topics.find((x) => x.id === topic);
  return t ? t[lang] : topic;
}
export function kindName(id: string, lang: Lang) {
  return tax.kinds.find((k) => k.id === id)?.[lang] ?? id;
}
export function evidenceName(id: string, lang: Lang) {
  return tax.evidence.find((k) => k.id === id)?.[lang] ?? id;
}
export const KINDS = tax.kinds;
export const EVIDENCE = tax.evidence;

export function formatDay(day: string, lang: Lang, style: "long" | "short" = "long") {
  const d = new Date(day + "T12:00:00Z");
  return d.toLocaleDateString(lang === "es" ? "es-AR" : "en-US", {
    weekday: style === "long" ? "long" : undefined,
    day: "numeric",
    month: style === "long" ? "long" : "short",
    year: style === "long" ? undefined : "numeric",
    timeZone: "UTC",
  });
}

export const num = (n: number, lang: Lang) => n.toLocaleString(lang === "es" ? "es-AR" : "en-US");

